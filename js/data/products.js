// Helper to look up a product by ID
function getProductById(id) {
  if (!id) return null;
  return GAMEVAULT_PRODUCTS.find(p => p.id === id) || null;
}

// Helper to get products by category
function getProductsByCategory(category) {
  if (!category || category === "all") return GAMEVAULT_PRODUCTS;
  return GAMEVAULT_PRODUCTS.filter(p => p.category === category);
}

// Helper to get flash deal items
function getFlashDeals() {
  return GAMEVAULT_PRODUCTS.filter(p => p.isFlashDeal);
}

// Helper to get featured items
function getFeaturedProducts(limit = 8) {
  return GAMEVAULT_PRODUCTS.filter(p => p.featured).slice(0, limit);
}
